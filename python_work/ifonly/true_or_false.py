# Test with strings
print("setting bird1 to 'oven bird'")
bird1 = 'oven bird'
print("setting bird2 to 'cat bird'")
bird2 = 'cat bird'
print(f"bird1 is {bird1} and bird2 is {bird2}")
print("Test if they are equal?")
print(f"Is bird1 equal to bird2? Result: {bird1 == bird2}")
print(f"So bird1 is not equal to bird2? Result: {bird1 != bird2}")
print(f"Is bird1 greater than bird2? Result: {bird1 > bird2}")
print(f"So then bird1 cannot be less than bird2? Result: {bird1 < bird2}")

