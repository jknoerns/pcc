# list of bicycle vendors
bicycles = ['trek','cannondale','redline','specialized']

print(bicycles)

# print the first element of the list
print("\nThe first element of the list...")
print(f"{bicycles[0]}")

# print in title case
print("\nThe first element of the list in title case...")
print(f"{bicycles[0].title()}")

# print the second element of the list
print("\nThe second element of the list in title case...")
print(f"{bicycles[1].title()}")

# print the forth element of the list
print("\nThe forth element of the list in title case...")
print(f"{bicycles[3].title()}")

# print the last element of the list reguardless of index...
print("\nThe last element of the list in title case...")
print(f"{bicycles[-1].title()}")
