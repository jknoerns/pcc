first_name = "Michelle"

# print first name variable
print(f"This is the variable first_name as stored in memory: {first_name}")

# print name in lowercase
print(f"This is your name in lowercase: {first_name.lower()}")

# print name in uppercase
print(f"This is your name in uppercase: {first_name.upper()}")

# print name in title case
print(f"This is your name in title case: {first_name.title()}")